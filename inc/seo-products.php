/** Автоматические Title и Description по названию и описанию товара. */
function exprinto_product_seo_auto( $product ) {
	$name  = $product->get_name();
	$short = preg_replace( '/,[^,]*$/u', '', $name ); // без последнего уточнения (цвет).
	if ( mb_strlen( $short ) > 52 ) {
		$short = mb_substr( $short, 0, 50 ) . '…';
	}
	$title = $short . ' — на заказ | Promark.by';
	$text  = wp_strip_all_tags( preg_replace( '/<\/(li|p)>/i', '. ', $product->get_short_description() ? $product->get_short_description() : $product->get_description() ) );
	$text  = trim( preg_replace( array( '/\s+/u', '/\.\s*\./u' ), array( ' ', '.' ), $text ) );
	$desc  = $name . '. ' . $text;
	if ( mb_strlen( $desc ) > 158 ) {
		$desc = rtrim( mb_substr( $desc, 0, 155 ), " ,.;—-" ) . '…';
	}
	return array( $title, $desc );
}

/** Новые товары: если Title / Description не заполнены — заполнить автоматически. */
add_action(
	'woocommerce_after_product_object_save',
	function ( $product ) {
		$id = $product->get_id();
		if ( ! $id || 'publish' !== $product->get_status() ) {
			return;
		}
		$t = get_post_meta( $id, '_ex_title', true );
		$d = get_post_meta( $id, '_ex_desc', true );
		if ( $t && $d ) {
			return;
		}
		list( $at, $ad ) = exprinto_product_seo_auto( $product );
		if ( ! $t ) {
			update_post_meta( $id, '_ex_title', $at );
		}
		if ( ! $d ) {
			update_post_meta( $id, '_ex_desc', $ad );
		}
	},
	20
);
